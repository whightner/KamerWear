const VIEW_LABELS = ["front view", "back view", "close-up detail"];

/** Builds a colour whose photos live in /images/products/<slug>/<colour>-<n>.webp. */
function color(
  productSlug: string,
  slug: string,
  name: string,
  swatch: string,
  noun: string,
  photoCount = 1,
): ProductColor {
  return {
    slug,
    name,
    swatch,
    images: Array.from({ length: photoCount }, (_, index) => ({
      src: `/images/products/${productSlug}/${slug}-${index + 1}.webp`,
      alt: `${name} ${noun}, ${VIEW_LABELS[index]}`,
    })),
  };
}

